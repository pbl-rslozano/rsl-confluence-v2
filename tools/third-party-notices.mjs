#!/usr/bin/env node
/**
 * third-party-notices.mjs — v2.8 WP20 (licence audit 14 Nov 2026): THIRD-PARTY-NOTICES.txt for every bundle.
 *
 *   node tools/third-party-notices.mjs --out apps/confluence/web/out/THIRD-PARTY-NOTICES.txt [--target html|tauri|capacitor]
 *   node tools/third-party-notices.mjs --check     exit 1 when a shipped component has no licence text (CI, release check)
 *   node tools/third-party-notices.mjs --rust      regenerate the Rust notices from `cargo metadata --locked` (needs cargo
 *                                                  and the crate sources; developer machine only)
 *
 * What is shipped (the notices list exactly these):
 *   - npm: the production closure of apps/confluence/web, packages/adapters/* and apps/confluence/mobile —
 *     `dependencies`, installed `optionalDependencies` and required `peerDependencies`, walked through node_modules
 *     with Node's resolution — minus BUILD_ONLY (compilers, image tooling, type definitions, browser data used only at
 *     build time). `@rsl/*` workspace packages are first-party (UNLICENSED) and only their dependencies are listed.
 *     Each package's own LICENSE/LICENCE/COPYING/NOTICE files are reproduced; a package without one uses a pinned text
 *     from tools/third-party-fallbacks/ (sources.json records where each came from, with its sha256).
 *   - fonts: the Fontsource packages above (their LICENSE carries the OFL text and copyright) and the menu-font subsets
 *     (public/fonts/menu/OFL.txt, written by tools/build-menu-fonts.py).
 *   - components: shadcn/ui (copied into src/components/ui); on mobile SQLCipher, LibTomCrypt, ZIPFoundation, AndroidX.
 *   - desktop (target tauri): the Rust crates from Cargo.lock (apps/confluence/desktop/src-tauri/THIRD-PARTY-NOTICES-rust.txt,
 *     generated by --rust) and the Microsoft WebView2 Runtime notice.
 * No network: everything is read from node_modules and committed files.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const PRODUCTION_ROOTS = ["apps/confluence/web", "packages/adapters/web", "packages/adapters/tauri", "packages/adapters/capacitor", "apps/confluence/mobile"];
export const FALLBACK_DIR = join(ROOT, "tools", "third-party-fallbacks");
export const RUST_DIR = "apps/confluence/desktop/src-tauri";
export const RUST_NOTICES = `${RUST_DIR}/THIRD-PARTY-NOTICES-rust.txt`;
export const RUST_INVENTORY = `${RUST_DIR}/third-party-crates.json`;
export const MENU_OFL = "apps/confluence/web/public/fonts/menu/OFL.txt";
export const TARGETS = ["html", "tauri", "capacitor"];

/** Build-time only: never copied into out/ or a bundle. Not walked further (their own dependencies are build-only too). */
export const BUILD_ONLY = [
  [/^sharp$|^@img\//, "image optimisation at build time (next/image is unoptimised in the static export)"],
  [/^@next\/swc-/, "Next.js compiler binary"],
  [/^@next\/env$/, "Next.js build/server environment loader"],
  [/^caniuse-lite$|^baseline-browser-mapping$/, "browser-support data used by the build"],
  [/^postcss$/, "CSS processing at build time"],
  [/^typescript$/, "type checker (peer of @web3icons/common)"],
  [/^@types\//, "TypeScript type definitions"],
  [/^@rollup\//, "bundler binary used by @stencil/core at build time"],
];
export function isBuildOnly(name) {
  for (const [re, why] of BUILD_ONLY) if (re.test(name)) return why;
  return null;
}

const LICENCE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([._-].*)?$/i;
const METADATA_ONLY = /\.spdx$/i; // LICENSE.spdx: copyright metadata, not a licence text
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const norm = (s) => s.replace(/\r\n/g, "\n").replace(/\s+$/, "") + "\n";

function resolveDep(fromDir, name) {
  for (let d = fromDir; ; d = dirname(d)) {
    const p = join(d, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return realpathSync(p);
    if (dirname(d) === d) return null;
  }
}

function licenceFiles(dir) {
  return readdirSync(dir).filter((f) => LICENCE_FILE.test(f) && statSync(join(dir, f)).isFile()).sort();
}

function licenceOf(j) {
  if (typeof j.license === "string") return j.license;
  if (j.license?.type) return j.license.type;
  if (Array.isArray(j.licenses)) return j.licenses.map((l) => l.type ?? l).join(" OR ");
  return "";
}

export function loadFallbacks(fallbackDir = FALLBACK_DIR) {
  const p = join(fallbackDir, "sources.json");
  return existsSync(p) ? readJson(p) : { files: {}, packages: {}, components: [], notices: [] };
}

/**
 * Production npm closure.
 * @returns {{ shipped: object[], buildOnly: object[], firstParty: string[] }}
 */
export function npmInventory({ root = ROOT, roots = PRODUCTION_ROOTS, fallbackDir = FALLBACK_DIR } = {}) {
  const fallbacks = loadFallbacks(fallbackDir);
  const seen = new Map();
  const buildOnly = new Map();
  const firstParty = new Set();
  const visitDeps = (dir, j) => {
    const peersOptional = j.peerDependenciesMeta ?? {};
    const deps = [
      ...Object.keys(j.dependencies ?? {}).map((n) => [n, false]),
      ...Object.keys(j.optionalDependencies ?? {}).map((n) => [n, true]),
      ...Object.keys(j.peerDependencies ?? {}).filter((n) => !peersOptional[n]?.optional).map((n) => [n, true]),
    ];
    for (const [name] of deps) {
      const at = resolveDep(dir, name);
      if (at) visit(at);
    }
  };
  const visit = (dir) => {
    const j = readJson(join(dir, "package.json"));
    const key = `${j.name}@${j.version}`;
    if (j.name?.startsWith("@rsl/")) {
      if (firstParty.has(key)) return;
      firstParty.add(key);
      return visitDeps(dir, j);
    }
    if (seen.has(key) || buildOnly.has(key)) return;
    const why = isBuildOnly(j.name);
    if (why) { buildOnly.set(key, { name: j.name, version: j.version, license: licenceOf(j), dir, reason: why, scope: "excluded" }); return; }
    const own = licenceFiles(dir);
    const fb = fallbacks.packages?.[key] ?? null;
    const texts = own.map((f) => ({ file: f, text: norm(readFileSync(join(dir, f), "utf8")), own: true }));
    if (fb) {
      for (const f of fb.files ?? []) {
        const p = join(fallbackDir, f);
        texts.push({ file: `tools/third-party-fallbacks/${f}`, text: existsSync(p) ? norm(readFileSync(p, "utf8")) : "", own: false, missing: !existsSync(p) });
      }
      if (fb.packageFiles) {
        const [sub, , file] = fb.packageFiles.split("/"); // "lib-vendor/*/LICENSE"
        const base = join(dir, sub);
        if (existsSync(base)) for (const d of readdirSync(base).sort()) {
          const p = join(base, d, file);
          if (existsSync(p)) texts.push({ file: `${sub}/${d}/${file}`, text: norm(readFileSync(p, "utf8")), own: true });
        }
      }
    }
    const hasLicenceText = texts.some((t) => t.text && !METADATA_ONLY.test(t.file));
    seen.set(key, {
      name: j.name, version: j.version, license: licenceOf(j), dir, scope: "required",
      repository: typeof j.repository === "string" ? j.repository : j.repository?.url ?? "",
      texts: hasLicenceText ? texts : [], ownFiles: own, fallback: fb, note: fb?.note ?? "",
    });
    visitDeps(dir, j);
  };
  for (const r of roots) {
    const dir = resolve(root, r);
    if (!existsSync(join(dir, "package.json"))) continue;
    const j = readJson(join(dir, "package.json"));
    firstParty.add(`${j.name}@${j.version ?? ""}`);
    for (const name of Object.keys(j.dependencies ?? {})) {
      const at = resolveDep(dir, name);
      if (at) visit(at);
    }
  }
  const sort = (a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name));
  return { shipped: [...seen.values()].sort(sort), buildOnly: [...buildOnly.values()].sort(sort), firstParty: [...firstParty].sort() };
}

/** Cargo.lock → [{ name, version }]. */
export function parseCargoLock(text) {
  return text.split("[[package]]").slice(1).map((b) => ({ name: b.match(/^name = "([^"]+)"/m)?.[1], version: b.match(/^version = "([^"]+)"/m)?.[1] })).filter((c) => c.name && c.version);
}

/** The Rust inventory must cover Cargo.lock exactly; every crate needs a licence text; MPL crates a source location. */
export function checkRustInventory(lockText, crates, { firstParty = ["rsl-confluence-desktop"] } = {}) {
  const findings = [];
  const have = new Map(crates.map((c) => [`${c.name}@${c.version}`, c]));
  for (const c of parseCargoLock(lockText)) {
    if (firstParty.includes(c.name)) continue;
    const e = have.get(`${c.name}@${c.version}`);
    if (!e) { findings.push(`${c.name}@${c.version}: in Cargo.lock but not in the Rust notices — run node tools/third-party-notices.mjs --rust`); continue; }
    if (!e.texts?.length) findings.push(`${c.name}@${c.version}: no licence text`);
    if (/\bMPL-2\.0\b/.test(e.license ?? "") && !e.source) findings.push(`${c.name}@${c.version}: MPL-2.0 without a source location`);
  }
  const locked = new Set(parseCargoLock(lockText).map((c) => `${c.name}@${c.version}`));
  for (const k of have.keys()) if (!locked.has(k)) findings.push(`${k}: in the Rust notices but not in Cargo.lock — regenerate`);
  return { ok: findings.length === 0, findings };
}

/** Mobile: SQLCipher must be named whenever the SQLite plugin ships. */
export function checkNativeNotices(shippedNames, nativeText) {
  const needs = shippedNames.includes("@capacitor-community/sqlite");
  const ok = !needs || /SQLCipher/.test(nativeText);
  return { ok, findings: ok ? [] : ["@capacitor-community/sqlite ships but the mobile notices do not name SQLCipher"] };
}

function readRustInventory(root) {
  const p = join(root, RUST_INVENTORY);
  if (!existsSync(p)) return null;
  return readJson(p).crates.map((c) => ({ ...c, texts: [...(c.files ?? []), ...(c.fallback ? [c.fallback] : [])] }));
}

function menuFontSection(root) {
  const p = join(root, MENU_OFL);
  return existsSync(p) ? norm(readFileSync(p, "utf8")) : "";
}

const RULE = "=".repeat(78);
const rule = (title) => `\n${RULE}\n${title}\n${RULE}\n`;

/**
 * @param {{ root?: string, roots?: string[], fallbackDir?: string, target?: "html"|"tauri"|"capacitor" }} [opts]
 * @returns {{ text: string, missing: string[], inventory: ReturnType<typeof npmInventory> }}
 */
export function buildNotices({ root = ROOT, roots = PRODUCTION_ROOTS, fallbackDir = FALLBACK_DIR, target = "html" } = {}) {
  if (!TARGETS.includes(target)) throw new Error(`unknown target ${target}`);
  const inventory = npmInventory({ root, roots, fallbackDir });
  const fallbacks = loadFallbacks(fallbackDir);
  const missing = inventory.shipped.filter((p) => !p.texts.length).map((p) => `${p.name}@${p.version}`);
  const components = (fallbacks.components ?? []).filter((c) => (c.targets ?? TARGETS).includes(target));
  const notices = (fallbacks.notices ?? []).filter((n) => (n.targets ?? TARGETS).includes(target));
  const rust = target === "tauri" && existsSync(join(root, RUST_NOTICES)) ? norm(readFileSync(join(root, RUST_NOTICES), "utf8")) : "";
  const fonts = menuFontSection(root);
  const out = [];
  out.push("rsL Confluence Terminal — third-party notices");
  out.push("");
  out.push("The app itself: Copyright rsLozano. All rights reserved (see LICENSE in the source repository).");
  out.push("It includes the open-source components below, each under its own licence, reproduced in full.");
  out.push(`Bundle: ${target === "html" ? "web / PWA" : target === "tauri" ? "desktop (Tauri)" : "Android / iPhone (Capacitor)"}.`);
  out.push(`npm packages shipped: ${inventory.shipped.length}`);
  out.push(`Other components: ${components.length}${rust ? " · Rust crates: see the desktop section" : ""}${fonts ? " · menu fonts (SIL OFL 1.1)" : ""}`);
  out.push("Generated by tools/third-party-notices.mjs from the installed packages; build-only tools are not shipped and not listed.");
  for (const n of notices) {
    out.push(rule(`Notice — ${n.id}`));
    out.push(n.text);
  }
  out.push(rule("npm packages (name@version — licence)"));
  for (const p of inventory.shipped) out.push(`${p.name}@${p.version} — ${p.license || "licence not declared"}`);
  for (const p of inventory.shipped) {
    out.push(rule(`${p.name}@${p.version} — ${p.license || "licence not declared"}${p.repository ? `\n${p.repository.replace(/^git\+/, "")}` : ""}`));
    if (p.note) out.push(`Note: ${p.note}\n`);
    for (const t of p.texts) {
      out.push(`--- ${t.own ? "" : "licence text from "}${t.file} ---`);
      out.push(t.text);
    }
  }
  if (fonts) {
    out.push(rule("Menu fonts (public/fonts/menu) — SIL OFL 1.1"));
    out.push(fonts);
  }
  for (const c of components) {
    out.push(rule(`${c.title} — ${c.license}`));
    if (c.note) out.push(`Note: ${c.note}\n`);
    for (const f of c.files) {
      const p = join(fallbackDir, f);
      out.push(`--- ${f.split("/").pop()} ---`);
      out.push(existsSync(p) ? norm(readFileSync(p, "utf8")) : "");
    }
  }
  if (rust) {
    out.push(rule("Desktop app — Rust crates (Cargo.lock)"));
    out.push(rust);
  }
  return { text: out.join("\n") + "\n", missing, inventory };
}

/**
 * Everything --check verifies. `skip` lets fixture tests leave out repository-wide parts.
 * @returns {{ ok: boolean, findings: string[], summary: string }}
 */
/** Characters of `text` that Windows code page 1252 cannot hold. The MSI (WiX) licence page shows
 *  bundle.licenseFile and fails with LGHT0311 on any of them (2.8.0 release build, 18 Nov 2026). */
const CP1252_HIGH = "€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ";
export function cp1252Unencodable(text) {
  const bad = new Set();
  for (const ch of text) {
    const c = ch.codePointAt(0);
    if (c < 0x80 || (c >= 0xa0 && c <= 0xff) || CP1252_HIGH.includes(ch)) continue;
    bad.add(ch);
  }
  return [...bad];
}

export function checkNotices({ root = ROOT, roots = PRODUCTION_ROOTS, fallbackDir = FALLBACK_DIR, skip = [] } = {}) {
  const findings = [];
  const fallbacks = loadFallbacks(fallbackDir);
  for (const [f, e] of Object.entries(fallbacks.files ?? {})) {
    const p = join(fallbackDir, f);
    if (!existsSync(p)) findings.push(`fallback ${f} missing`);
    else if (e.sha256 !== sha256(readFileSync(p))) findings.push(`fallback ${f}: sha256 differs from sources.json (licence texts are copied, never edited)`);
    if (!e.source) findings.push(`fallback ${f}: no source recorded`);
  }
  const referenced = [
    ...Object.values(fallbacks.packages ?? {}).flatMap((p) => p.files ?? []),
    ...(fallbacks.components ?? []).flatMap((c) => c.files ?? []),
  ];
  for (const f of referenced) if (!fallbacks.files?.[f]) findings.push(`fallback ${f} used but not recorded in sources.json`);
  const built = buildNotices({ root, roots, fallbackDir, target: "html" });
  for (const m of built.missing) findings.push(`${m}: no licence text (no LICENSE file in the package and no entry in tools/third-party-fallbacks/sources.json)`);
  for (const p of built.inventory.shipped) for (const t of p.texts) if (t.missing) findings.push(`${p.name}@${p.version}: fallback ${t.file} missing`);
  if (!skip.includes("fonts")) {
    for (const f of ["inter", "space-grotesk", "jetbrains-mono", "noto-naskh-arabic", "noto-nastaliq-urdu"]) {
      if (!built.inventory.shipped.some((p) => p.name === `@fontsource/${f}` && p.texts.some((t) => /SIL Open Font License/i.test(t.text)))) findings.push(`@fontsource/${f}: OFL text not found`);
    }
  }
  if (!skip.includes("menuFonts")) {
    const ofl = menuFontSection(root);
    if (!/SIL OPEN FONT LICENSE/.test(ofl) || !/PERMISSION & CONDITIONS/.test(ofl)) findings.push(`${MENU_OFL}: full SIL OFL 1.1 text missing (python3 tools/build-menu-fonts.py)`);
  }
  if (!skip.includes("native")) {
    const cap = buildNotices({ root, roots, fallbackDir, target: "capacitor" });
    findings.push(...checkNativeNotices(cap.inventory.shipped.map((p) => p.name), cap.text).findings);
    if (!/shadcn/.test(built.text)) findings.push("shadcn/ui notice missing");
  }
  if (!skip.includes("rust")) {
    const lockPath = join(root, RUST_DIR, "Cargo.lock");
    const crates = readRustInventory(root);
    if (!crates) findings.push(`${RUST_INVENTORY} missing — run node tools/third-party-notices.mjs --rust`);
    else {
      findings.push(...checkRustInventory(readFileSync(lockPath, "utf8"), crates).findings);
      const rustText = existsSync(join(root, RUST_NOTICES)) ? readFileSync(join(root, RUST_NOTICES), "utf8") : "";
      for (const [id, re] of [["MPL-2.0", /Mozilla Public License Version 2\.0/], ["CDLA-Permissive-2.0", /Community Data License Agreement/], ["Unicode-3.0", /UNICODE LICENSE V3/]]) {
        if (crates.some((c) => c.license?.includes(id)) && !re.test(rustText)) findings.push(`${RUST_NOTICES}: ${id} text missing`);
      }
      const tauri = buildNotices({ root, roots, fallbackDir, target: "tauri" });
      if (!/WebView2 Runtime/.test(tauri.text)) findings.push("desktop notices: WebView2 notice missing");
      const confPath = join(root, RUST_DIR, "tauri.conf.json");
      if (existsSync(confPath)) {
        const bundle = readJson(confPath).bundle ?? {};
        const res = Array.isArray(bundle.resources) ? bundle.resources : Object.keys(bundle.resources ?? {});
        if (!res.includes("THIRD-PARTY-NOTICES-rust.txt")) findings.push("tauri.conf.json: bundle.resources lacks THIRD-PARTY-NOTICES-rust.txt");
        if (!bundle.licenseFile || !existsSync(join(root, RUST_DIR, bundle.licenseFile))) findings.push("tauri.conf.json: bundle.licenseFile missing or not found");
        else {
          const bad = cp1252Unencodable(readFileSync(join(root, RUST_DIR, bundle.licenseFile), "utf8"));
          if (bad.length) findings.push(`${bundle.licenseFile}: characters outside code page 1252 break the Windows MSI licence page (${bad.join(" ")})`);
        }
      }
    }
  }
  const summary = `${built.inventory.shipped.length} npm packages, ${built.inventory.buildOnly.length} build-only left out, ${Object.keys(fallbacks.files ?? {}).length} pinned fallback texts`;
  return { ok: findings.length === 0, findings, summary };
}

/* ---------------- Rust: regenerate from cargo metadata (developer machine) ---------------- */

const PREFER = ["MIT", "Apache-2.0", "BSD-3-Clause", "ISC", "Zlib", "Unlicense", "BSL-1.0", "MPL-2.0", "Unicode-3.0", "CDLA-Permissive-2.0"];
const SPDX_FALLBACK = { MIT: "texts/MIT.txt", "Apache-2.0": "texts/Apache-2.0.txt", "BSD-3-Clause": "texts/BSD-3-Clause.txt", "MPL-2.0": "texts/MPL-2.0.txt", "Unicode-3.0": "texts/Unicode-3.0.txt", "CDLA-Permissive-2.0": "texts/CDLA-Permissive-2.0.txt" };

function electLicence(expr) {
  const alts = expr.replace(/\//g, " OR ").split(/\s+OR\s+/).map((s) => s.replace(/[()]/g, "").trim());
  for (const id of PREFER) if (alts.includes(id)) return id;
  return alts[0];
}

/** Pure: cargo metadata JSON → { crates, text }. `readDir(dir)` lists licence files; `readFile` reads one. */
export function rustNoticesFromMetadata(meta, { fallbackDir = FALLBACK_DIR } = {}) {
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const rootId = meta.resolve.root;
  const scope = new Map();
  const stack = [[rootId, "required"]];
  while (stack.length) {
    const [id, k] = stack.pop();
    const prev = scope.get(id);
    if (prev === "required" || (prev && k !== "required")) continue;
    scope.set(id, k);
    for (const d of nodes.get(id)?.deps ?? []) {
      const kinds = d.dep_kinds.map((x) => x.kind);
      if (kinds.every((x) => x === "dev")) continue;
      const pkg = byId.get(d.pkg);
      const procMacro = pkg.targets.some((t) => t.kind.includes("proc-macro"));
      stack.push([d.pkg, k === "required" && kinds.includes(null) && !procMacro ? "required" : "excluded"]);
    }
  }
  const crates = [];
  const textUsers = new Map(); // text → [crate labels]
  const addText = (text, label) => { const t = norm(text); textUsers.set(t, [...(textUsers.get(t) ?? []), label]); };
  for (const [id, sc] of scope) {
    if (id === rootId) continue;
    const p = byId.get(id);
    const dir = dirname(p.manifest_path);
    const files = licenceFiles(dir);
    const license = p.license ?? (p.license_file ? `see ${p.license_file}` : "");
    const label = `${p.name} ${p.version}`;
    const c = { name: p.name, version: p.version, license, repository: p.repository ?? "", scope: sc, files };
    if (/\bMPL-2\.0\b/.test(license)) c.source = `https://crates.io/crates/${p.name}/${p.version}`;
    for (const f of files) addText(readFileSync(join(dir, f), "utf8"), label);
    if (!files.length) {
      const id2 = electLicence(license);
      const fb = SPDX_FALLBACK[id2];
      if (fb) {
        c.fallback = `tools/third-party-fallbacks/${fb}`;
        if (p.authors?.length) c.authors = p.authors;
        addText(readFileSync(join(fallbackDir, fb), "utf8"), label);
      }
    }
    crates.push(c);
  }
  // MPL-2.0 texts must be present even if a crate ships none (selectors).
  crates.sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version, undefined, { numeric: true }) : a.name.localeCompare(b.name)));
  const lines = [];
  lines.push(`Rust crates compiled into the desktop app (from Cargo.lock, all platforms): ${crates.length}.`);
  lines.push("Each crate is listed with its licence; the licence texts follow, each printed once with the crates that ship it.");
  lines.push("MPL-2.0 crates: the source code of the exact version used is available at the \"Source code\" address shown.");
  lines.push("Crates that ship no licence file are shown with the SPDX text of their declared licence and the authors from their Cargo.toml.");
  lines.push("");
  for (const c of crates) {
    lines.push(`${c.name} ${c.version} — ${c.license}${c.repository ? ` — ${c.repository}` : ""}${c.scope === "excluded" ? " (build-time only)" : ""}`);
    if (c.source) lines.push(`    Source code: ${c.source} (download: https://crates.io/api/v1/crates/${c.name}/${c.version}/download)`);
    if (c.fallback) lines.push(`    No licence file in the crate; licence text: ${c.fallback.split("/").pop()}${c.authors ? `; authors (Cargo.toml): ${c.authors.join(", ")}` : ""}`);
  }
  let k = 0;
  for (const [text, users] of [...textUsers.entries()].sort((a, b) => a[1][0].localeCompare(b[1][0]))) {
    k++;
    lines.push("");
    lines.push("-".repeat(78));
    lines.push(`Licence text ${k} — used by: ${users.join(", ")}`);
    lines.push("-".repeat(78));
    lines.push(text);
  }
  return { crates, text: lines.join("\n").replace(/\n+$/, "") + "\n" };
}

function regenerateRust(root = ROOT) {
  const meta = JSON.parse(execFileSync("cargo", ["metadata", "--locked", "--format-version", "1"], { cwd: join(root, RUST_DIR), maxBuffer: 256 * 1024 * 1024, encoding: "utf8" }));
  const { crates, text } = rustNoticesFromMetadata(meta);
  writeFileSync(join(root, RUST_NOTICES), text);
  writeFileSync(join(root, RUST_INVENTORY), JSON.stringify({
    "@note": "Generated by node tools/third-party-notices.mjs --rust from `cargo metadata --locked` (WP20). Release check R24 and --check compare it with Cargo.lock. Do not edit.",
    crates: crates.map(({ name, version, license, repository, scope, source, files, fallback, authors }) => ({ name, version, license, repository, scope, ...(source ? { source } : {}), files, ...(fallback ? { fallback } : {}), ...(authors ? { authors } : {}) })),
  }, null, 1) + "\n");
  console.log(`Rust notices: ${crates.length} crates → ${RUST_NOTICES} (${Math.round(text.length / 1024)} KiB), ${RUST_INVENTORY}`);
}

/* ---------------- CLI ---------------- */
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const argv = process.argv.slice(2);
  const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
  if (argv.includes("--rust")) regenerateRust();
  if (argv.includes("--check")) {
    const r = checkNotices();
    console.log(`${r.ok ? "PASS" : "FAIL"}  third-party notices  ${r.summary}`);
    for (const f of r.findings) console.log(`  ${f}`);
    if (!r.ok) process.exit(1);
  }
  const out = arg("--out");
  if (out) {
    const target = arg("--target") ?? "html";
    const { text, missing, inventory } = buildNotices({ target });
    if (missing.length) { console.error(`No licence text for: ${missing.join(", ")}`); process.exit(1); }
    mkdirSync(dirname(resolve(out)), { recursive: true });
    writeFileSync(resolve(out), text);
    console.log(`THIRD-PARTY-NOTICES (${target}): ${inventory.shipped.length} npm packages, ${Math.round(text.length / 1024)} KiB → ${relative(process.cwd(), resolve(out)).split(sep).join("/")}`);
  }
  if (!argv.length) { console.error("usage: third-party-notices.mjs --out <file> [--target html|tauri|capacitor] | --check | --rust"); process.exit(2); }
}
